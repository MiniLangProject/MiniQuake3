import mq3.client.playable_combat_view as combat

function require(ok,text) if not ok then return error(7549,text) end if;return 1 end function

function main(args)
  c=0
  c=c+require(combat.FIRE_FLASH_MS==90 and combat.RECOIL_MS==180,"fire timings")
  c=c+require(combat.HIT_MARK_MS==160 and combat.DAMAGE_MARK_MS==350 and combat.KILL_MARK_MS==900,"feedback timings")
  view=combat.state("")
  c=c+require(view.weaponName=="MACHINEGUN","default weapon")
  c=c+require(view.score==0 and view.kills==0 and view.deaths==0,"initial score")
  c=c+require(view.shots==0 and view.hits==0,"initial accuracy")
  named=combat.state("RAILGUN");c=c+require(named.weaponName=="RAILGUN","named weapon")
  c=c+require(combat.clampNonnegative(-3)==0 and combat.clampNonnegative(8)==8,"nonnegative clamp")
  combat.setScore(view,7);c=c+require(view.score==7,"score setter")
  combat.fire(view,1000);c=c+require(view.lastFire==1000 and view.shots==1,"fire event")
  combat.fire(view,1010);c=c+require(view.shots==2,"shot accumulation")
  combat.registerHit(view,1020);c=c+require(view.lastHit==1020 and view.hits==1,"hit event")
  combat.takeDamage(view,1030,23,-5);c=c+require(view.damageAmount==23 and view.damageSide==-1,"left damage")
  combat.takeDamage(view,1040,-2,9);c=c+require(view.damageAmount==0 and view.damageSide==1,"right damage and clamp")
  combat.takeDamage(view,1050,5,0);c=c+require(view.damageSide==0,"center damage")
  combat.registerKill(view,1060,8);c=c+require(view.kills==1 and view.score==8 and view.lastKill==1060,"kill event")
  combat.registerDeath(view);c=c+require(view.deaths==1,"death event")
  c=c+require(combat.remaining(100,100,100)==1000,"pulse begins full")
  c=c+require(combat.remaining(150,100,100)==500,"pulse midpoint")
  c=c+require(combat.remaining(199,100,100)==10,"pulse final tick")
  c=c+require(combat.remaining(200,100,100)==0,"pulse expires")
  c=c+require(combat.remaining(99,100,100)==0,"future event inactive")
  fresh=combat.state("MG");combat.fire(fresh,2000);combat.registerHit(fresh,2000);combat.takeDamage(fresh,2000,10,-1);combat.registerKill(fresh,2000,1)
  p=combat.pulse(fresh,2000);c=c+require(p.recoil==1000 and p.muzzle==1000 and p.hit==1000,"fresh fire pulses")
  c=c+require(p.damage==1000 and p.kill==1000,"fresh combat pulses")
  p=combat.pulse(fresh,2090);c=c+require(p.muzzle==0 and p.recoil==500,"flash expires before recoil")
  p=combat.pulse(fresh,2160);c=c+require(p.hit==0 and p.recoil>0,"hit expires before recoil")
  p=combat.pulse(fresh,2350);c=c+require(p.damage==0 and p.kill>0,"damage expires before kill")
  p=combat.pulse(fresh,2900);c=c+require(p.kill==0,"kill expires")
  small=combat.layout(320,200);large=combat.layout(1920,1080)
  c=c+require(small.centerX==160 and small.centerY==100,"small center")
  c=c+require(small.weaponWidth==64 and small.weaponHeight>66 and small.weaponHeight<67,"small weapon dimensions")
  c=c+require(large.weaponWidth==210 and large.weaponHeight==220,"weapon dimension caps")
  c=c+require(large.weaponX==855 and large.weaponY==860,"large weapon anchor")
  c=c+require(try(combat.layout(319,200)) is error and try(combat.layout(320,199)) is error,"small surface rejected")
  c=c+require(try(combat.setScore(void,1)) is error,"score state required")
  c=c+require(try(combat.fire(void,1)) is error,"fire state required")
  c=c+require(try(combat.registerHit(void,1)) is error,"hit state required")
  c=c+require(try(combat.takeDamage(void,1,1,0)) is error,"damage state required")
  c=c+require(try(combat.registerKill(void,1,1)) is error,"kill state required")
  c=c+require(try(combat.registerDeath(void)) is error,"death state required")
  c=c+require(try(combat.pulse(void,1)) is error,"pulse state required")
  c=c+require(try(combat.draw(void,320,200,0)) is error,"draw state required")
  print("PASS: "+str(c)+" playable-combat-view contracts");return 0
end function
