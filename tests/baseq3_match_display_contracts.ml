import mq3.client.baseq3_match_display as display

function require(ok,text) if not ok then return error(7584,text) end if;return 1 end function

function main(args)
  count=0
  count=count+require(display.BIGCHAR_WIDTH==16 and display.BIGCHAR_HEIGHT==16,"retail bigchar geometry")
  count=count+require(display.ATLAS_COLUMNS==16 and display.ATLAS_ROWS==16,"retail atlas grid")
  count=count+require(display.glyphCell("A")[0]==1 and display.glyphCell("A")[1]==4,"ASCII atlas cell")
  count=count+require(display.glyphCell("0")[0]==0 and display.glyphCell("0")[1]==3,"digit atlas cell")
  count=count+require(try(display.glyphCell("AB")) is error,"single glyph validation")
  count=count+require(display.printLength("ARENA")==5,"plain print length")
  count=count+require(display.printLength("^1RED ^7WHITE")==9,"color escapes excluded")
  count=count+require(display.printLength("^^")==2,"escaped caret remains visible")
  count=count+require(display.colorFor("1")==[255,0,0] and display.colorFor("2")==[0,255,0],"Quake colors")
  count=count+require(display.colorFor("7")==[255,255,255],"white Quake color")
  count=count+require(display.timerText(1000,1000)=="0:00","clock starts at zero")
  count=count+require(display.timerText(1000,62499)=="1:01","clock truncates milliseconds")
  count=count+require(display.timerText(1000,3601999)=="60:00","clock minutes are unbounded")
  count=count+require(display.timerText(2000,1000)=="0:00","clock clamps before level start")
  warmup=display.countdown(4000,1000)
  count=count+require(warmup.text=="Starts in: 4" and warmup.charWidth==16 and warmup.charHeight==24,"early countdown")
  warmup=display.countdown(4000,1500)
  count=count+require(warmup.text=="Starts in: 3" and warmup.second==2 and warmup.charWidth==20,"count three pulse")
  warmup=display.countdown(4000,2500)
  count=count+require(warmup.text=="Starts in: 2" and warmup.charWidth==24,"count two pulse")
  warmup=display.countdown(4000,3500)
  count=count+require(warmup.text=="Starts in: 1" and warmup.charWidth==28,"count one pulse")
  count=count+require(display.countdown(4000,4001)==void,"finished countdown hidden")
  count=count+require(display.countdown(0,0)==void,"disabled countdown hidden")
  center=display.centerPrint("FIRST\nSECOND",1000,144,16,3000)
  count=count+require(center.lines==2 and center.y==144 and center.charWidth==16,"centerprint line state")
  count=count+require(display.centerAlpha(center,999)==0,"centerprint before start")
  count=count+require(display.centerAlpha(center,1000)==255,"centerprint begins opaque")
  count=count+require(display.centerAlpha(center,3800)==255,"centerprint fade boundary")
  count=count+require(display.centerAlpha(center,3900)==127,"centerprint 200ms fade")
  count=count+require(display.centerAlpha(center,4000)==0,"centerprint expires")
  defaults=display.centerPrint("FIGHT!",1,-1,0,0)
  count=count+require(defaults.y==display.CENTER_DEFAULT_Y and defaults.charWidth==16 and defaults.duration==3000,"centerprint defaults")
  count=count+require(try(display.centerPrint("bad",-1,1,1,1)) is error,"centerprint time validation")
  count=count+require(try(display.load(void,216)) is error,"archive required")
  count=count+require(try(display.load(defaults,-1)) is error,"texture slot lower bound")
  count=count+require(try(display.load(defaults,256)) is error,"texture slot upper bound")
  rows=display.scoreRows(7,3,2)
  count=count+require(len(rows)==2 and rows[0].localPlayer and rows[0].name=="YOU","winning player ranks first")
  count=count+require(rows[0].score==7 and rows[0].deaths==2,"player scoreboard values")
  count=count+require(rows[1].name=="SARGE BOTS" and rows[1].score==3,"enemy aggregate values")
  rows=display.scoreRows(2,5,4)
  count=count+require(not rows[0].localPlayer and rows[0].score==5,"leading enemies rank first")
  rows=display.scoreRows(5,5,1)
  count=count+require(rows[0].localPlayer,"ties keep local player first")
  count=count+require(try(display.scoreRows(-1,0,0)) is error,"negative player score rejected")
  count=count+require(try(display.scoreRows(0,0,-1)) is error,"negative deaths rejected")
  print("PASS: "+str(count)+" Baseq3 match-display contracts");return 0
end function
