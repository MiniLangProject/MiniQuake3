import mq3.client.playable_match as match

function req(ok,text) if not ok then return error(7621,text) end if;return 1 end function
function main(args)
  c=0;s=match.create(10,5,3000)
  c=c+req(s.phase==match.PHASE_WAITING and s.fragLimit==10,"initial waiting state")
  c=c+req(match.start(s,1000)==match.PHASE_WARMUP and s.matchStart==4000,"warmup schedule")
  u=match.update(s,1000,0,0);c=c+req(u.message=="3" and u.phase==match.PHASE_WARMUP,"three countdown")
  c=c+req(match.update(s,2001,0,0).message=="2","two countdown")
  c=c+req(match.update(s,3001,0,0).message=="1","one countdown")
  u=match.update(s,4000,0,0);c=c+req(u.changed and u.message=="FIGHT!" and u.phase==match.PHASE_ACTIVE,"fight transition")
  c=c+req(u.remainingSeconds==300 and u.clock=="00:00","active clock begins")
  u=match.update(s,65432,3,2);c=c+req(u.phase==match.PHASE_ACTIVE and u.clock=="01:01","active clock advances")
  u=match.update(s,70000,10,7);c=c+req(u.phase==match.PHASE_INTERMISSION and u.message=="YOU WIN","fraglimit win")
  c=c+req(match.update(s,70001,10,7).message=="YOU WIN","intermission persists")
  loss=match.create(2,1,0);match.start(loss,0);u=match.update(loss,10,1,2)
  c=c+req(u.message=="YOU LOSE" and loss.winner==match.WINNER_ENEMIES,"enemy fraglimit loss")
  tied=match.create(99,1,0);match.start(tied,100);u=match.update(tied,60100,4,4)
  c=c+req(u.message=="TIED GAME" and tied.intermissionAt==60100,"timelimit tie")
  c=c+req(match.secondsCeil(0)==0 and match.secondsCeil(1)==1 and match.secondsCeil(1001)==2,"ceiling seconds")
  c=c+req(match.clock(tied,60100)=="01:00","minute clock")
  c=c+req(match.twoDigits(0)=="00" and match.twoDigits(9)=="09" and match.twoDigits(10)=="10","clock padding")
  longWarmup=match.create(1,1,5000);match.start(longWarmup,0)
  c=c+req(match.update(longWarmup,0,0,0).message=="PREPARE TO FIGHT","long warmup message")
  c=c+req(match.announcerCue("3")==match.ANNOUNCER_THREE,"three announcer cue")
  c=c+req(match.announcerCue("2")==match.ANNOUNCER_TWO,"two announcer cue")
  c=c+req(match.announcerCue("1")==match.ANNOUNCER_ONE,"one announcer cue")
  c=c+req(match.announcerCue("FIGHT!")==match.ANNOUNCER_FIGHT,"fight announcer cue")
  c=c+req(match.announcerCue("YOU WIN")==match.ANNOUNCER_NONE,"result has no countdown cue")
  c=c+req(try(match.create(0,1,0)) is error,"fraglimit validation")
  c=c+req(try(match.create(1,0,0)) is error,"timelimit validation")
  c=c+req(try(match.start(void,0)) is error,"missing start state rejected")
  c=c+req(try(match.update(s,-1,0,0)) is error,"negative time rejected")
  print("PASS: "+str(c)+" playable match contracts");return 0
end function
