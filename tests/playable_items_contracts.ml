import mq3.client.playable_items as items
import mq3.client.playable_weapon_inventory as inventory

function require(ok,text) if not ok then return error(7502,text) end if;return 1 end function
function entity(name,origin) return [["classname",name],["origin",origin]] end function

function main(args)
  c=0
  entities=[entity("item_health_small","0 0 0"),entity("item_health","100 0 0"),entity("item_health_large","200 0 0"),entity("item_health_mega","300 0 0"),entity("item_armor_shard","400 0 0"),entity("item_armor_combat","500 0 0"),entity("item_armor_body","600 0 0"),entity("ammo_rockets","700 0 0"),entity("ammo_lightning","800 0 0"),entity("weapon_rocketlauncher","900 0 0"),entity("weapon_lightning","1000 0 0"),entity("info_player_start","1100 0 0"),entity("ammo_shells","broken")]
  state=items.fromEntities(entities,42.0)
  c=c+require(len(state.items)==11,"recognized valid entities")
  c=c+require(items.activeCount(state)==11,"all items initially active")
  c=c+require(state.items[0].kind=="health" and state.items[0].amount==5 and state.items[0].cap==200,"small health definition")
  c=c+require(state.items[1].amount==25 and state.items[1].cap==100,"normal health definition")
  c=c+require(state.items[2].amount==50 and state.items[2].cap==100,"large health definition")
  c=c+require(state.items[3].amount==100 and state.items[3].cap==200,"mega health definition")
  c=c+require(state.items[4].amount==5 and state.items[5].amount==50 and state.items[6].amount==100,"armor definitions")
  c=c+require(state.items[7].amount==5 and state.items[8].amount==60,"ammo definitions")
  c=c+require(state.items[9].kind=="weapon" and state.items[9].respawnMs==5000,"weapon definition")
  items.setStats(state,90,0,0,"weapon_machinegun")
  events=items.update(state,[0.0,0.0,0.0],1000)
  c=c+require(len(events)==1 and events[0].amount==5 and state.stats.health==95,"small health pickup")
  c=c+require(not state.items[0].active and state.items[0].respawnAt==36000,"health respawn schedule")
  c=c+require(len(items.update(state,[0.0,0.0,0.0],35999))==0,"inactive item ignored")
  c=c+require(items.activeCount(state)==10,"inactive count")
  c=c+require(len(items.update(state,[99.0,0.0,0.0],36000))==1,"respawn and nearby normal health")
  c=c+require(state.items[0].active and state.stats.health==100,"respawned item remains when capped")
  items.setStats(state,199,199,199,"weapon_machinegun")
  e=items.update(state,[300.0,0.0,0.0],40000)
  c=c+require(len(e)==1 and state.stats.health==200 and e[0].amount==1,"mega overhealth cap")
  e=items.update(state,[600.0,0.0,0.0],41000)
  c=c+require(len(e)==1 and state.stats.armor==200 and e[0].amount==1,"armor cap")
  e=items.update(state,[700.0,0.0,0.0],42000)
  c=c+require(len(e)==1 and state.stats.ammo==200 and e[0].amount==1,"ammo cap")
  c=c+require(len(items.update(state,[800.0,0.0,0.0],43000))==0,"full ammo blocks pickup")
  items.setStats(state,100,0,200,"weapon_machinegun")
  e=items.update(state,[900.0,0.0,0.0],44000)
  c=c+require(len(e)==1 and state.stats.weapon=="weapon_rocketlauncher" and e[0].amount==0,"new weapon at ammo cap")
  c=c+require(len(items.update(state,[1000.0,0.0,0.0],45000))==1 and state.stats.weapon=="weapon_lightning","weapon switching")
  c=c+require(len(items.update(state,[1043.0,0.0,0.0],46000))==0,"outside pickup radius")
  c=c+require(items.definition("ITEM_HEALTH_CUSTOM")[0]=="health","case-insensitive health prefix")
  c=c+require(items.definition("ammo_custom")[1]==10,"generic ammo prefix")
  c=c+require(items.definition("weapon_custom")[0]=="weapon","generic weapon prefix")
  c=c+require(items.definition("holdable_medkit")==void,"unrecognized entity")
  capped=items.fromEntities([entity("item_health","0 0 0")],42.0);items.setStats(capped,100,0,0,"")
  c=c+require(len(items.update(capped,[0.0,0.0,0.0],1))==0 and capped.items[0].active,"capped health stays present")
  c=c+require(try(items.fromEntities(void,42.0)) is error,"missing entities rejected")
  c=c+require(try(items.fromEntities([],0.0)) is error,"bad radius rejected")
  c=c+require(try(items.setStats(void,1,2,3,"")) is error,"missing state rejected")
  c=c+require(try(items.setStats(state,-1,0,0,"")) is error,"negative stats rejected")
  c=c+require(try(items.update(state,[0.0,0.0],0)) is error,"bad position rejected")
  c=c+require(try(items.update(state,[0.0,0.0,0.0],-1)) is error,"negative time rejected")
  inv=inventory.create(false)
  separate=items.fromEntities([entity("ammo_rockets","0 0 0"),entity("weapon_rocketlauncher","100 0 0"),entity("ammo_bullets","200 0 0")],42.0)
  items.setStats(separate,100,0,inventory.ammoFor(inv,inventory.WP_MACHINEGUN),"weapon_machinegun")
  c=c+require(items.canTakeInventory(separate.items[0],separate.stats,inv),"rocket ammo can be taken independently")
  e=items.updateInventory(separate,[0.0,0.0,0.0],1000,inv,false)
  c=c+require(len(e)==1 and e[0].amount==5,"inventory ammo pickup emitted")
  c=c+require(inventory.ammoFor(inv,inventory.WP_ROCKET_LAUNCHER)==5,"rocket pool increased")
  c=c+require(inventory.ammoFor(inv,inventory.WP_MACHINEGUN)==100,"machinegun pool unchanged")
  c=c+require(separate.stats.ammo==100 and separate.stats.weapon=="weapon_machinegun","HUD follows selected pool")
  e=items.updateInventory(separate,[100.0,0.0,0.0],2000,inv,false)
  c=c+require(len(e)==1 and e[0].amount==5,"weapon reaches stock quantity")
  c=c+require(inventory.owns(inv,inventory.WP_ROCKET_LAUNCHER),"weapon ownership granted")
  c=c+require(inv.selectedWeapon==inventory.WP_ROCKET_LAUNCHER,"pickup selects weapon")
  c=c+require(separate.stats.weapon=="weapon_rocketlauncher" and separate.stats.ammo==10,"selected weapon stats synchronized")
  e=items.updateInventory(separate,[200.0,0.0,0.0],3000,inv,false)
  c=c+require(len(e)==1 and inventory.ammoFor(inv,inventory.WP_MACHINEGUN)==150,"bullet pickup uses machinegun pool")
  c=c+require(separate.stats.ammo==10,"off-weapon ammo leaves HUD pool unchanged")
  inventory.select(inv,inventory.WP_MACHINEGUN);separate.stats.weapon="weapon_machinegun";separate.stats.ammo=150
  e=items.updateInventory(separate,[100.0,0.0,0.0],7000,inv,false)
  c=c+require(len(e)==1 and inventory.ammoFor(inv,inventory.WP_ROCKET_LAUNCHER)==11,"repeated weapon grants one stock shot")
  c=c+require(inv.selectedWeapon==inventory.WP_MACHINEGUN and separate.stats.weapon=="weapon_machinegun","repeated weapon does not autoswitch")
  c=c+require(try(items.updateInventory(separate,[0.0,0.0],0,inv,false)) is error,"inventory path validates position")
  print("PASS: "+str(c)+" playable-item contracts");return 0
end function
