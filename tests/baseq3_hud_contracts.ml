import mq3.client.baseq3_hud as hud
import mq3.renderer.playable_materials as materials

function require(ok,text) if not ok then return error(7581,text) end if;return 1 end function
function fakeCatalog()
  image=materials.Image(1,1,bytes(4,255));assets=[];slot=220
  for each item in hud.descriptors() assets=assets+[hud.Asset(item[0],item[1]+".tga",image,slot)];slot=slot+1 end for
  return hud.Catalog(assets,220,len(assets))
end function

function main(args)
  count=0;definitions=hud.descriptors();catalog=fakeCatalog()
  count=count+require(len(definitions)==hud.REQUIRED_TEXTURES,"bounded complete artwork set")
  count=count+require(definitions[0][0]=="number_0" and definitions[10][0]=="number_minus","Baseq3 number shader order")
  count=count+require(definitions[11][1]=="gfx/2d/crosshaira","stock crosshair path")
  count=count+require(hud.find(catalog,"FACE").imageName=="models/players/sarge/icon_default.tga","case-insensitive asset lookup")
  count=count+require(hud.find(catalog,"missing")==void,"unknown asset")
  count=count+require(hud.clampField(1000,3)==999 and hud.clampField(-100,3)==-99,"three-column clamp")
  count=count+require(hud.clampField(100,2)==99 and hud.clampField(-10,2)==-9,"two-column clamp")
  count=count+require(hud.fieldStart(0.0,3,7)==66.0,"right aligned one-digit field")
  count=count+require(hud.fieldStart(185.0,3,100)==187.0,"full field inset")
  count=count+require(hud.numberKey("-")=="number_minus" and hud.numberKey("7")=="number_7","number artwork selection")
  count=count+require(hud.weaponIconKey("MACHINEGUN")=="weapon_machinegun","weapon display name")
  count=count+require(hud.weaponIconKey("weapon_rocketlauncher")=="weapon_rocketlauncher","weapon classname")
  count=count+require(hud.weaponIconKey("grenade launcher")=="weapon_grenadelauncher","grenade display name")
  count=count+require(hud.weaponIconKey("lightning gun")=="weapon_lightning","lightning display name")
  count=count+require(hud.weaponIconKey("rail")=="weapon_railgun","rail display name")
  count=count+require(hud.weaponIconKey("BFG10K")=="weapon_bfg","BFG display name")
  count=count+require(hud.ammoIconKey("machinegun")=="ammo_machinegun","machinegun ammo icon")
  count=count+require(hud.ammoIconKey("weapon_shotgun")=="ammo_shotgun","shotgun ammo icon")
  count=count+require(hud.ammoIconKey("grenadelauncher")=="ammo_grenadelauncher","grenade ammo icon")
  count=count+require(hud.ammoIconKey("rocket launcher")=="ammo_rocketlauncher","rocket ammo icon")
  count=count+require(hud.ammoIconKey("weapon_lightning")=="ammo_lightning","lightning ammo icon")
  count=count+require(hud.ammoIconKey("railgun")=="ammo_railgun","rail ammo icon")
  count=count+require(hud.ammoIconKey("plasma gun")=="ammo_plasmagun","plasma ammo icon")
  count=count+require(hud.ammoIconKey("bfg")=="ammo_bfg","BFG ammo icon")
  count=count+require(hud.ammoIconKey("unknown")=="ammo_machinegun","unknown weapon ammo fallback")
  count=count+require(hud.pickupIconKey("item_armor_combat")=="armor","yellow armor pickup")
  count=count+require(hud.pickupIconKey("ITEM_HEALTH_MEGA")=="item_health_mega","health pickup")
  count=count+require(hud.pickupIconKey("weapon_shotgun")=="weapon_shotgun","weapon pickup")
  placement=hud.layout(640,480)
  count=count+require(placement.scaleX==1.0 and placement.scaleY==1.0,"canonical Baseq3 coordinates")
  count=count+require(hud.statusHeadX(placement)==285.0,"original status head x coordinate")
  count=count+require(hud.STATUS_HEAD_Y==420.0 and hud.STATUS_HEAD_SIZE==60.0,"original 60px status head box")
  placement=hud.layout(960,540)
  count=count+require(placement.scaleX==1.5 and placement.scaleY==1.125,"responsive virtual screen")
  count=count+require(try(hud.layout(319,240)) is error,"small surface rejected")
  value=hud.state(100,25,50,"machinegun",3,4,1)
  count=count+require(value.health==100 and value.armor==25 and value.ammo==50,"combat values retained")
  count=count+require(value.weapon=="machinegun" and value.score==3 and value.kills==4 and value.deaths==1,"score state retained")
  count=count+require(len(value.ownedWeapons)==0 and value.weaponSelectTime==0,"selection strip initially hidden")
  selected=hud.selectWeapons(value,["weapon_machinegun","weapon_shotgun"],[42,0],"weapon_shotgun",1200)
  count=count+require(selected==2,"selection inventory accepted")
  count=count+require(value.weapon=="weapon_shotgun" and value.weaponSelectTime==1200,"selection state retained")
  count=count+require(value.weaponAmmo[0]==42 and value.weaponAmmo[1]==0,"selection ammo retained")
  count=count+require(try(hud.selectWeapons(value,["weapon_machinegun"],[],"weapon_machinegun",1300)) is error,"selection shape validated")
  count=count+require(hud.weaponDisplayName("weapon_rocketlauncher")=="ROCKET LAUNCHER","selection display name")
  count=count+require(hud.WEAPON_SELECT_TIME==1400 and hud.SELECTED_WEAPON_ICON_SIZE>hud.WEAPON_ICON_SIZE,"selection timing and emphasis")
  hud.pickup(value,"item_health","25 HEALTH",900)
  count=count+require(value.pickupClass=="item_health" and value.pickupName=="25 HEALTH" and value.pickupTime==900,"pickup feedback")
  hud.frag(value,1000);count=count+require(value.fragTime==1000,"frag feedback")
  count=count+require(try(hud.load(void,217,39)) is error,"archive required")
  count=count+require(try(hud.load(catalog,-1,39)) is error,"negative slot rejected")
  count=count+require(try(hud.load(catalog,240,39)) is error,"native slot overflow rejected")
  count=count+require(try(hud.load(catalog,217,38)) is error,"texture budget rejected")
  count=count+require(hud.findKey("b",["a","b","c"]),"set membership")
  count=count+require(not hud.findKey("z",["a","b","c"]),"set miss")
  print("PASS: "+str(count)+" Baseq3 HUD contracts");return 0
end function
