import mq3.qcommon.config_persistence as config

struct Context writes prints bindings succeed end struct
function req(value,label) if not value then return error(499,"Cvar config contract: "+label) end if;return 1 end function
function writeFile(context,name,text) context.writes=context.writes+[[name,text]];return context.succeed end function
function bindingText(context) return context.bindings end function
function output(context,text) context.prints=context.prints+[text];return void end function
function fixture()
  registry=cvar.create();host=config.services();context=Context([],[],"bind w +forward\n",true)
  host.context=context;host.writeFn=writeFile;host.bindingTextFn=bindingText;host.printFn=output
  return [config.create(registry,host),context]
end function
