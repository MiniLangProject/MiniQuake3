"""Generate the literal playerState layout from the pinned source (no engine code).

The differential oracle independently checks every C offset and field value.
"""
import json
import re
from toolchain import ROOT
from inventory import sha

def main():
    source=ROOT / 'Quake-III-Arena-original-source/code/game/q_shared.h'
    body=source.read_text().split('typedef struct playerState_s {')[1].split('} playerState_t;')[0]
    body=re.sub(r'//[^\n]*|/\*.*?\*/','',body,flags=re.S)
    sizes={'MAX_PS_EVENTS':2,'MAX_STATS':16,'MAX_PERSISTANT':16,'MAX_POWERUPS':16,'MAX_WEAPONS':16,'3':3}
    fields=[]; offset=0
    for decl in body.split(';'):
        if not decl.strip(): continue
        match=re.fullmatch(r'\s*(int|vec3_t)\s+(\w+)(?:\[(\w+)\])?\s*',decl)
        if not match: raise ValueError(decl)
        kind,name,size=match.groups();count=3 if kind=='vec3_t' else sizes[size] if size else 1
        fields.append({'name':name,'type':'float' if kind=='vec3_t' else 'int','count':count,'offset':offset})
        offset+=4*count
    lines=['// Copyright (C) 1999-2005 Id Software, Inc.','// SPDX-License-Identifier: GPL-2.0-or-later',
           '// Generated by scripts/generate_playerstate.py from pinned q_shared.h.',
           '// Binary codec is a local comparison/storage layout, not network serialization.',
           'package mq3.game.playerstate','import mq3.compat.numeric as n',f'const BYTE_SIZE = {offset}',
           'struct PlayerState',*['  '+f['name'] for f in fields],'end struct','', 'function create()']
    defaults=[]
    for f in fields:
        zero='0.0' if f['type']=='float' else '0'
        defaults.append(zero if f['count']==1 else '['+','.join([zero]*f['count'])+']')
    lines+=['  return PlayerState('+','.join(defaults)+')','end function','','function copy(source)','  return PlayerState(']
    for f in fields:
        value='source.'+f['name']
        if f['count']>1: value='['+','.join(value+f'[{i}]' for i in range(f['count']))+']'
        lines+=['    '+value+',']
    lines[-1]=lines[-1][:-1]
    lines+=['  )','end function','','function load(data, offset)',
            '  if offset < 0 or offset+BYTE_SIZE > len(data) then return error(470,"Truncated playerState") end if',
            '  ps = create()']
    for f in fields:
        values=[]
        for i in range(f['count']):
            v=f'n.readI32(data,offset+{f["offset"]+i*4})'
            if f['type']=='float': v='n.bitsFloat('+v+')'
            values.append(v)
        lines+=['  ps.'+f['name']+' = '+(values[0] if len(values)==1 else '['+','.join(values)+']')]
    lines+=['  return ps','end function','','function words(ps)','  return [']
    for f in fields:
        values=['ps.'+f['name']+(f'[{i}]' if f['count']>1 else '') for i in range(f['count'])]
        values=[('n.floatBits('+v+')') if f['type']=='float' else 'n.u32('+v+')' for v in values]
        lines+=['    '+','.join(values)+',']
    lines[-1]=lines[-1][:-1]
    lines+=['  ]','end function','']
    (ROOT / 'src/mq3/game/playerstate.ml').write_text('\n'.join(lines))
    (ROOT / 'docs/reference/playerstate.json').write_text(json.dumps({'source_sha256':sha(source),'size':offset,'fields':fields},indent=2)+'\n')
    print(f'Generated {len(fields)} fields / {offset} bytes')

if __name__=='__main__':main()
