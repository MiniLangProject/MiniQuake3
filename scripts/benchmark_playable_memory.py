"""Sample only an owned Retail replay process; retain memory evidence on failure.

Title FPS is smoothed diagnostic text, not performance acceptance. Moving mode
uses the exact productive-loop regression binary generated by
test_ingame_controls_render.py. No desktop input is synthesized here.
"""
import argparse,ctypes as c,hashlib,json,os,re,subprocess,time
from pathlib import Path
root=Path(__file__).resolve().parents[1]
parser=argparse.ArgumentParser(description=__doc__)
parser.add_argument('--output',type=Path,required=True)
parser.add_argument('--binary',type=Path,default=root/'build/MiniQuake3.exe')
parser.add_argument('--mode',choices=('neutral','moving','controls'),default='neutral')
parser.add_argument('--frames',type=int,default=30000)
parser.add_argument('--timeout',type=int,default=600)
parser.add_argument('--max-work-ms',type=float,help='Fail if the reported worst work frame exceeds this latency limit')
args=parser.parse_args()
if os.name!='nt':parser.error('Windows process memory APIs are required')
if args.frames<20 or args.timeout<1:parser.error('frames must be at least20; timeout must be positive')
out=args.output.resolve();out.mkdir(parents=True,exist_ok=True)
binary=args.binary.resolve();binary_hash=hashlib.sha256(binary.read_bytes()).hexdigest()
class Mem(c.Structure):
    _fields_=[('cb',c.c_ulong),('faults',c.c_ulong)]+[(k,c.c_size_t) for k in ['peakWorking','working','peakPaged','paged','peakNonpaged','nonpaged','pagefile','peakPagefile','private']]
kernel=c.windll.kernel32;kernel.OpenProcess.restype=c.c_void_p
kernel.CloseHandle.argtypes=[c.c_void_p]
c.windll.psapi.GetProcessMemoryInfo.argtypes=[c.c_void_p,c.POINTER(Mem),c.c_ulong]
cbtype=c.WINFUNCTYPE(c.c_bool,c.c_void_p,c.c_void_p)
def title(pid):
    result=[]
    def visit(hwnd,_):
        owner=c.c_ulong();c.windll.user32.GetWindowThreadProcessId(c.c_void_p(hwnd),c.byref(owner))
        if owner.value==pid:
            text=c.create_unicode_buffer(1024);c.windll.user32.GetWindowTextW(c.c_void_p(hwnd),text,1024)
            if text.value:result.append(text.value)
        return True
    c.windll.user32.EnumWindows(cbtype(visit),0);return result
with (out/'stdout.log').open('w') as stdout,(out/'stderr.log').open('w') as stderr,(out/'samples.jsonl').open('w') as samples:
    if args.mode=='neutral':cmd=[str(binary),'--play-qvm-smoke',str(root/'build/baseq3/pak0.pk3'),'maps/q3dm1.bsp',str(root/'build/reference/qvms'),str(args.frames)]
    else:cmd=[str(binary),str(root/'build/baseq3/pak0.pk3'),str(root/'build/reference/qvms'),args.mode,str(args.frames)]
    process=subprocess.Popen(cmd,cwd=root,stdout=stdout,stderr=stderr)
    handle=kernel.OpenProcess(0x410,False,process.pid);started=time.monotonic();last=0
    records=0;peak_private=0;first_warm=None;final=None;timed_out=False
    try:
        if not handle:raise c.WinError()
        while process.poll() is None:
            elapsed=time.monotonic()-started
            mem=Mem();mem.cb=c.sizeof(mem)
            if not c.windll.psapi.GetProcessMemoryInfo(handle,c.byref(mem),mem.cb):
                if process.poll() is not None:break
                raise c.WinError()
            record={'seconds':round(elapsed,2),'rss_mb':round(mem.working/1048576,2),'private_mb':round(mem.private/1048576,2),'titles':title(process.pid)}
            samples.write(json.dumps(record)+'\n');samples.flush()
            records+=1;final=record;peak_private=max(peak_private,record['private_mb'])
            if elapsed>=40 and first_warm is None:first_warm=record
            if elapsed-last>=20:print(record,flush=True);last=elapsed
            if elapsed>args.timeout:timed_out=True;process.terminate();break
            time.sleep(1)
        print('exit',process.returncode,flush=True)
    finally:
        if process.poll() is None:process.terminate();process.wait()
        kernel.CloseHandle(handle)
    stdout.flush();frame_match=re.search(r'QVM preview:.*frames=(\d+)',(out/'stdout.log').read_text(encoding='utf-8',errors='replace'))
    completed_frames=int(frame_match[1]) if frame_match else 0
    loop_match=re.search(r'workMax=(\S+)ms',(out/'stdout.log').read_text(encoding='utf-8',errors='replace'))
    work_max_ms=float(loop_match[1]) if loop_match else None
    latency_passed=args.max_work_ms is None or (work_max_ms is not None and work_max_ms<=args.max_work_ms)
    completed=not timed_out and process.returncode==0 and completed_frames==args.frames
    report={'completed':completed,'binary_sha256':binary_hash,'mode':args.mode,'requested_frames':args.frames,'completed_frames':completed_frames,'returncode':process.returncode,'timed_out':timed_out,'elapsed_seconds':time.monotonic()-started,'samples':records,'peak_private_mb':peak_private,'first_warm':first_warm,'final':final,'scope':'Process-private/working memory and smoothed title FPS; inspect raw samples and replay output, not a leak or FPS acceptance assertion.'}
    (out/'memory.json').write_text(json.dumps(report,indent=2)+'\n')
    if args.max_work_ms is not None:
        report['latency_acceptance']={'max_work_ms':args.max_work_ms,'measured_work_max_ms':work_max_ms,'passed':latency_passed}
        (out/'memory.json').write_text(json.dumps(report,indent=2)+'\n')
    if not completed or not latency_passed:raise RuntimeError('Owned replay failed, ended early or exceeded the latency limit; evidence retained in '+str(out))
