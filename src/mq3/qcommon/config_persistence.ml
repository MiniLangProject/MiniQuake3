// Baseq3 common.c configuration persistence around Cvar_WriteVariables.
package mq3.qcommon.config_persistence
import mq3.qcommon.cvar as cvar
import mq3.qcommon.command_buffer as command

/// Maximum character capacity reserved for a Quake asset path.
const MAX_QPATH=64

/// Services record for qcommon.config_persistence, containing `writeFn`, `bindingTextFn`, `printFn`, `context`.
struct Services
  /// Host callback that writes data through the host output interface.
  writeFn
  /// Host callback that serializes the current input bindings for configuration persistence.
  bindingTextFn
  /// Host callback that prints configuration-save progress and write failures.
  printFn
  /// Caller-supplied data associated with configuration-file writing, key-binding serialization, and
  /// save diagnostics.
  context
end struct

/// State record for qcommon.config_persistence, containing `registry`, `services`, `fullyInitialized`.
struct State
  /// Registry used to resolve registered names, handles, or runtime definitions.
  registry
  /// File-writing, binding-serialization, and diagnostic services used to save configuration.
  services
  /// True when initialization is complete and automatic configuration writes are allowed.
  fullyInitialized
end struct

/// Create `mq3.qcommon.config_persistence.Services` with writeFn=void; bindingTextFn=void; printFn=void; context=void.
function services() return Services(void,void,void,void) end function
/// Create `mq3.qcommon.config_persistence.State` with registry=registry; services=host; fullyInitialized=false.
/// @param registry Initial `registry` field stored in the returned or constructed `mq3.qcommon.config_persistence.State` record.
/// @param host Initial `services` field stored in the returned or constructed `mq3.qcommon.config_persistence.State` record.
function create(registry,host) return State(registry,host,false) end function

/// Emit config persistence in qcommon.config_persistence.
/// @param state Record exposing `services`.
/// @param text Text used in `state.services.printFn(state.services.context, text)`.
function emit(state,text)
  if state.services!=void and state.services.printFn!=void then state.services.printFn(state.services.context,text) end if
  return void
end function

/// Copy text in qcommon.config_persistence; the normal completion returns `decode(slice(data, 0, count))`.
/// @param text Text used in `bytes(text)`.
/// @param capacity Capacity used in `(capacity < 1)` and `(capacity - 1)`.
function copyText(text,capacity)
  if capacity<1 then return "" end if
  data=bytes(text);count=len(data);if count>=capacity then count=capacity-1 end if
  return decode(slice(data,0,count))
end function

// Q_strncpyz followed by COM_DefaultExtension, both constrained by MAX_QPATH.
/// @param name Text passed as `text` to `mq3.qcommon.config_persistence.copyText`.
function configFilename(name)
  result=copyText(name,MAX_QPATH);data=bytes(result);index=len(data)-1
  while index>=0 and data[index]!=47
    if data[index]==46 then return result end if
    index=index-1
  end while
  return copyText(result+".cfg",MAX_QPATH)
end function

/// Compute config text in qcommon.config_persistence; the normal completion returns `(output + cvar.writeVariables(state.registry))`.
/// @param state Record exposing `services`, `registry`.
function configText(state)
  output="// generated by quake, do not modify\n"
  if state.services!=void and state.services.bindingTextFn!=void then
    bindings=state.services.bindingTextFn(state.services.context)
    if bindings!=void then output=output+bindings end if
  end if
  return output+cvar.writeVariables(state.registry)
end function

/// Write config to file in qcommon.config_persistence; the normal completion returns `true`.
///
/// Validation failures include `Configuration persistence requires registry and write service`.
/// @param state Record exposing `registry`, `services`.
/// @param filename Filename used in `("Couldn't write " + filename)` and `(("Couldn't write " + filename) + ".\n")`.
/// @param reportFailure Whether to print a diagnostic if the write fails. Defaults to true.
function writeConfigToFile(state,filename,reportFailure=true)
  if state==void or state.registry==void or state.services==void or state.services.writeFn==void then
    return error(3513,"Configuration persistence requires registry and write service")
  end if
  written=state.services.writeFn(state.services.context,filename,configText(state))
  if not written then
    if reportFailure then emit(state,"Couldn't write "+filename+".\n") end if
    return false
  end if
  return true
end function

// Com_WriteConfiguration: archive dirtiness is consumed before attempting the
// write, matching the original failure behavior.
/// @param state Record exposing `fullyInitialized`, `registry`.
/// @param reportFailure Whether to report a write failure. Defaults to true.
function writeConfiguration(state,reportFailure=true)
  if state==void or not state.fullyInitialized then return false end if
  if (state.registry.modifiedFlags & cvar.ARCHIVE)==0 then return false end if
  state.registry.modifiedFlags=state.registry.modifiedFlags & ~cvar.ARCHIVE
  return writeConfigToFile(state,"q3config.cfg",reportFailure)
end function

/// Write config command in qcommon.config_persistence; the normal completion returns `writeConfigToFile(state, filename)`.
/// @param state State passed as `state` to `mq3.qcommon.config_persistence.emit`.
/// @param commandState State passed as `state` to `mq3.qcommon.command_buffer.argc`.
function writeConfigCommand(state,commandState)
  if command.argc(commandState)!=2 then emit(state,"Usage: writeconfig <filename>\n");return false end if
  filename=configFilename(command.argv(commandState,1));emit(state,"Writing "+filename+".\n")
  return writeConfigToFile(state,filename)
end function

// Cmd_AddCommand("writeconfig", Com_WriteConfig_f).  The command registry
// owns the association so several isolated engine runtimes can coexist in
// tests and tools without a process-global configuration pointer.
/// @param commandState Command state passed as `commandState` to `mq3.qcommon.config_persistence.writeConfigCommand`.
/// @param state State passed as `state` to `mq3.qcommon.config_persistence.writeConfigCommand`.
function commandCallback(commandState,state)
  if state==void then return error(3513,"writeconfig command is not bound") end if
  return writeConfigCommand(state,commandState)
end function

/// Test install command in qcommon.config_persistence; the normal completion returns `true`.
///
/// Validation failures include `Configuration persistence requires registry and write service`; `Configuration persistence requires command state`; `writeconfig command already registered`.
/// @param state Record exposing `registry`, `services`.
/// @param commandState State passed as `state` to `mq3.qcommon.command_buffer.addContextCommand`.
function installCommand(state,commandState)
  if state==void or state.registry==void or state.services==void or state.services.writeFn==void then return error(3513,"Configuration persistence requires registry and write service") end if
  if commandState==void then return error(3513,"Configuration persistence requires command state") end if
  if not command.addContextCommand(commandState,"writeconfig",commandCallback,state) then return error(3513,"writeconfig command already registered") end if
  return true
end function
